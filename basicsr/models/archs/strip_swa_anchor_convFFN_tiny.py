class Agent_Attn(nn.Module):
    def __init__(self, dim, num_heads, mlp_ratio,
                 convffn_kernel_size = 5,
                 reso=64, idx=0,
                 qkv_bias=True,
                 act_layer=nn.GELU,
                 norm_layer=nn.LayerNorm,
                 window_size=7,
                 window_shift=False,
                 stripe_size=[8, 8],
                 stripe_groups=[None, None],
                 stripe_shift=False,
                 stripe_type="H",
                 qkv_proj_type="linear",
                 anchor_proj_type="separable_conv",
                 anchor_one_stage=True,
                 anchor_window_down_factor=1,
                 drop=0.0,
                 attn_drop=0.0,
                 drop_path=0.0,
                 pretrained_stripe_size=[0, 0],
                 res_scale=1.0,
                 euclidean_dist=False,
                 args=None,
                 ):
        super(Agent_Attn, self).__init__()
        self.stripe_shift = stripe_shift
        self.stripe_type = stripe_type
        self.window_size = window_size
        self.window_shift = window_shift
        self.args = args
        if self.stripe_type == "W":
            self.stripe_size = stripe_size[::-1]
            self.stripe_groups = stripe_groups[::-1]
        else:
            self.stripe_size = stripe_size
            self.stripe_groups = stripe_groups
        self.mlp_ratio = mlp_ratio
        self.res_scale = res_scale

        self.norm1 = norm_layer(dim)
        self.norm2 = norm_layer(dim)
        self.convffn_kernel_size = convffn_kernel_size
        # win and shift win 交替
        reso = reso
        self.attn = AgentAnchorAttention(dim, reso,  num_heads,
                                         window_size,
                                         window_shift,
                                         self.stripe_size,
                                         self.stripe_groups,
                                         stripe_shift,
                                         qkv_bias,
                                         qkv_proj_type,
                                         anchor_proj_type,
                                         anchor_one_stage,
                                         anchor_window_down_factor,
                                         attn_drop,
                                         drop,
                                         pretrained_stripe_size,
                                         euclidean_dist,
                                         args,
                                         )

        mlp_hidden_dim = int(dim * mlp_ratio)
        mlp_hidden_dim = mlp_hidden_dim + mlp_hidden_dim%2
        self.convffn = ConvFFN(in_features=dim, hidden_features=mlp_hidden_dim, kernel_size=convffn_kernel_size,
                               act_layer=act_layer)
        # self.convffn = MLP_gate_rgt(in_features=dim, hidden_features=mlp_hidden_dim, out_features=dim,
        #                             act_layer=act_layer)

    def _get_table_index_mask(self, all_table_index_mask):
        table_index_mask = {
            "table_w": all_table_index_mask["table_w"],
            "index_w": all_table_index_mask["index_w"],
        }
        if self.stripe_type == "W":
            table_index_mask["table_s"] = all_table_index_mask["table_sv"]
            table_index_mask["index_a2w"] = all_table_index_mask["index_sv_a2w"]
            table_index_mask["index_w2a"] = all_table_index_mask["index_sv_w2a"]
        else:
            table_index_mask["table_s"] = all_table_index_mask["table_sh"]
            table_index_mask["index_a2w"] = all_table_index_mask["index_sh_a2w"]
            table_index_mask["index_w2a"] = all_table_index_mask["index_sh_w2a"]
        if self.window_shift:
            table_index_mask["mask_w"] = all_table_index_mask["mask_w"]
        else:
            table_index_mask["mask_w"] = None
        if self.stripe_shift:
            if self.stripe_type == "W":
                table_index_mask["mask_a2w"] = all_table_index_mask["mask_sv_a2w"]
                table_index_mask["mask_w2a"] = all_table_index_mask["mask_sv_w2a"]
            else:
                table_index_mask["mask_a2w"] = all_table_index_mask["mask_sh_a2w"]
                table_index_mask["mask_w2a"] = all_table_index_mask["mask_sh_w2a"]
        else:
            table_index_mask["mask_a2w"] = None
            table_index_mask["mask_w2a"] = None
        return table_index_mask

    def forward(self, x, all_table_index_mask):
        table_index_mask = self._get_table_index_mask(all_table_index_mask)
        b, c, H, W = x.shape
        # h, w = x_size
        # b, n, c = x.shape
        x_size = (H, W)
        x = rearrange(x, 'b c h w-> b (h w) c')
        x = x + self.attn(self.norm1(x),x_size,table_index_mask) * self.res_scale
        x = x + self.convffn(self.norm2(x), H, W)
        x = rearrange(x, 'b (h w) c-> b c h w', h=H, w=W)

        return x

class dwconv(nn.Module):
    def __init__(self, hidden_features, kernel_size=5):
        super(dwconv, self).__init__()
        self.depthwise_conv = nn.Sequential(
            nn.Conv2d(hidden_features, hidden_features, kernel_size=kernel_size, stride=1, padding=(kernel_size - 1) // 2, dilation=1,
                      groups=hidden_features), nn.GELU())
        self.hidden_features = hidden_features

    def forward(self,x,x_size):
        x = x.transpose(1, 2).view(x.shape[0], self.hidden_features, x_size[0], x_size[1]).contiguous()  # b Ph*Pw c
        x = self.depthwise_conv(x)
        x = x.flatten(2).transpose(1, 2).contiguous()
        return x


class TransformerBlock(nn.Module):
    def __init__(self, img_size, dim, num_heads, depth, ffn_expansion_factor, split_size = [8, 32],
                 stripe_size=[8, 8],
                 stripe_groups=[None, None],
                 window_size=7,
                 stripe_shift=False,
                 qkv_proj_type="linear",
                 anchor_proj_type="avgpool",
                 anchor_one_stage=True,
                 anchor_window_down_factor=1,
                 drop=0.0,
                 attn_drop=0.0,
                 norm_layer=nn.LayerNorm,
                 pretrained_stripe_size=[0, 0],
                 init_method="r",
                 euclidean_dist=False,
                 args=None,
                 ):
        super(TransformerBlock, self).__init__()
        self.dim = dim
        self.input_resolution = to_2tuple(img_size)

        self.blocks = nn.ModuleList()

        for i in range(depth):
            if i % 2 == 0:
                block = Window_Attn(dim, num_heads, ffn_expansion_factor, convffn_kernel_size=5, reso =img_size,
                                    idx=i, split_size = split_size, qkv_bias = True,
                                    norm_layer=nn.LayerNorm)
            else:
                block = Agent_Attn(dim=dim, num_heads=num_heads, mlp_ratio=ffn_expansion_factor,
                convffn_kernel_size = 5,
                reso = img_size, idx = i,
                qkv_bias = True,
                norm_layer = norm_layer,
                window_size=window_size,
                window_shift=i % 2 == 0,
                stripe_size=stripe_size,
                stripe_groups=stripe_groups,
                stripe_type="H" if i % 4 == 1 else "W",
                stripe_shift=i % 4 in [2, 3] if stripe_shift else False,
                   qkv_proj_type=qkv_proj_type,
                   anchor_proj_type=anchor_proj_type,
                   anchor_one_stage=anchor_one_stage,
                   anchor_window_down_factor=anchor_window_down_factor,
                   drop=drop,
                   attn_drop=attn_drop,
                   pretrained_stripe_size=pretrained_stripe_size,
                   res_scale=0.1 if init_method == "r" else 1.0,
                                   euclidean_dist=euclidean_dist,
                   args=args,
                   )


            self.blocks.append(block)

    
    def forward(self, x,table_index_mask):
        x_size = x.shape[2]
        i = 0
        for blk in self.blocks:
            if i % 2 == 0:
                x = blk(x)
            else:
                x = blk(x, table_index_mask)
            i = i +1

        return x
       
